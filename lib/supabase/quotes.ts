// Delete quote from Supabase (requires owner_token or authenticated user)
export async function deleteQuoteFromSupabase(
  id: string,
  ownerToken: string
): Promise<{ success: boolean; error?: string }> {
  const supabase = getSupabase();
  if (!supabase) {
    return { success: false, error: "Supabase not configured" };
  }

  try {
    const { data: { user } } = await supabase.auth.getUser();

    if (user) {
      // Authenticated: Use standard RLS delete
      const { error } = await supabase
        .from("quotes")
        .delete()
        .eq("id", id); // RLS checks user_id

      if (error) throw error;
    } else {
      // Anonymous: Use secure RPC
      const { data: success, error } = await supabase.rpc("delete_quote_anon", {
        p_id: id,
        p_token: ownerToken,
      });

      if (error) throw error;
      if (!success) return { success: false, error: "Quote not found or access denied" };
    }

    return { success: true };
  } catch (err) {
    return { success: false, error: "Failed to delete from cloud" };
  }
}

// Get all quotes from Supabase (for a list of owner tokens)
export async function getQuotesByOwnerTokens(ownerTokens: string[]): Promise<Quote[]> {
  const supabase = getSupabase();
  if (!supabase || ownerTokens.length === 0) {
    return [];
  }

  try {
    const { data, error } = await supabase
      .from("quotes")
      .select("*")
      .in("owner_token", ownerTokens)
      .order("created_at", { ascending: false });

    if (error || !data) {
      return [];
    }

    return (data as SupabaseQuoteRow[]).map(fromSupabaseFormat);
  } catch {
    return [];
  }
}
